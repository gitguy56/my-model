# =============================================================================
# What we'll build:
#   - A loop that runs hundreds of times and teaches the model from data
#
# The loop does three things every iteration:
#   1. Forward pass  — model makes a prediction
#   2. Loss          — we measure how wrong it was (cross-entropy loss)
#   3. Backward pass — gradients flow back through the network (autograd)
#   4. Optimizer step — weights nudge in the right direction (SGD / Adam)
#
# Concepts covered:
#   - loss function / cross-entropy
#   - gradient descent
#   - learning rate
#   - overfitting
#
